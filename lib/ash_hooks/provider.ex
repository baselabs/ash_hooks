defmodule AshHooks.Provider do
  @moduledoc """
  Behavior for inbound webhook providers.

  A provider verifies a request's signature, parses its event type, and handles
  its decoded payload. Optional callbacks resolve per-connection secrets,
  declare an authenticated timestamp, or identify a complete delivery.
  For HTTP protocols, optional `handshake/1` and `response/1` callbacks let
  `AshHooks.Plug` answer subscription challenges and sender-specific acknowledgments.
  Neither callback is generated by `use AshHooks.Provider`; absence means it
  is not implemented.

  Most providers describe the sender's scheme in configuration:

      defmodule MyApp.Webhooks.Orders do
        use AshHooks.Provider,
          verify: [algorithm: :hmac_sha256, signature: {:header, "x-orders-signature"}]
      end

  `AshHooks.Provider.Scheme` documents every option, and the
  [Verify any sender](verify-any-sender.md) guide has recipes for common
  signature shapes. A scheme that configuration cannot express implements
  `verify_signature/3` with the primitives in `AshHooks.Provider.Signature`.

  Configured providers return generic typed events (`AshHooks.Provider.Event`).
  Override `parse_event_type/1` and `handle_event/2` when ingress must classify
  events and execute application actions. Make those actions idempotent:
  durable ingress claims prevent overlapping ownership, but cannot make a remote
  side effect and the ledger update one transaction.
  """

  alias AshHooks.Provider.{Event, Scheme}

  @type raw_body :: binary()
  @type signature_header_value :: binary()
  @type webhook_secret :: binary()
  @type signature_algorithm :: :hmac_sha256 | :hmac_sha512
  @type signature_error :: :invalid_signature | :no_webhook_secret | :stale_timestamp
  @type parse_error :: :unknown_event_type | :malformed_payload
  @type http_response :: {pos_integer(), [{String.t(), String.t()}], iodata()}
  @type ingest_outcome :: {:ok, :created | :duplicate, struct()} | {:error, term()}
  @type handshake_request :: %{
          method: String.t(),
          query_params: map(),
          headers: [{String.t(), String.t()}],
          raw_body: raw_body() | nil
        }

  @doc """
  Optional HTTP handshake, called by `AshHooks.Plug` after resolving the source
  and capturing raw bytes, before method refusal or signature verification.

  Receives the method, query params decoded with `Plug.Conn.Query.decode/1`,
  ordered request headers, and exact raw body. Return
  `{:respond, status, headers, body}` to send a challenge response without any
  ledger write, or `:deliver` to continue. Response header names must be lowercase,
  as required by Plug. The callback must authenticate any challenge as required
  by the sender's protocol; delivery verification has not run yet.
  """
  @callback handshake(handshake_request()) ::
              {:respond, pos_integer(), [{String.t(), String.t()}], iodata()} | :deliver

  @doc """
  Optional HTTP acknowledgment policy. Receives exactly the outcome returned by
  `AshHooks.Ingress.ingest/4`. Return `{status, headers, body}` or `:default`.

  An implemented response takes precedence over the plug's `:respond` policy;
  `:default` falls through. Plug refusals and handshake responses never invoke
  this callback. Response header names must be lowercase. A custom 503 owns its
  headers, including any retry hint.
  """
  @callback response(ingest_outcome()) :: http_response() | :default

  @optional_callbacks handshake: 1, response: 1

  @typedoc """
  The request context `verify_signature/3` receives as its second argument.
  Carries everything any provider's signature scheme can need:

    * `:signature`: the signature header value the host passed, or `nil`; for a
      `signature_source/0` of `:body`, the raw body.
    * `:headers`: the request headers as a map. When the host passed the
      ordered list from `conn.req_headers`, names are lowercased and repeated
      lines are joined with `", "`; a host-supplied map arrives unchanged.
    * `:header_list`: every request header line as `{name, value}`, in
      arrival order with repeated lines kept, when the host passed a list
      (names lowercased); for a host-supplied map, its binary entries.
    * `:method`: the uppercase HTTP method, for schemes that sign over it.
      `nil` when the caller does not supply it.
    * `:request_uri`: the exact request URI the provider signed. `nil` when
      not supplied.
    * `:tenant`: the ingest tenant when the ledger is multitenant, `nil`
      otherwise. A provider whose custody is per-tenant (per-connection
      secrets keyed by organization) reads it here.
    * `:replay_window_seconds`: the declaration override when configured;
      absent when the provider should use its own default.

  A provider whose scheme needs only the signature reads `:signature` and
  ignores the rest.
  """
  @type verify_context :: %{
          optional(:replay_window_seconds) => pos_integer(),
          signature: signature_header_value() | nil,
          headers: %{optional(String.t()) => String.t()},
          header_list: [{String.t(), String.t()}],
          method: String.t() | nil,
          request_uri: String.t() | nil,
          tenant: term()
        }

  @typedoc """
  Where a provider's webhook signing secret lives:

    * `:app_level`: resolves the inbound declaration's secret source, which may
      be application-wide or tenant-aware. This is the default.
    * `:per_connection`: uses the provider's secret callback for the connection.
  """
  @type webhook_secret_scope :: :app_level | :per_connection

  @callback verify_signature(raw_body(), verify_context(), webhook_secret()) ::
              :ok | {:error, signature_error()}

  @doc """
  Resolves the signing secret used to verify an inbound webhook.

  The secret SOURCE is provider-dependent, so it lives with the provider
  module rather than in the generic ingress. App-level providers use the declaration's source, which can be tenant-aware;
  per-connection providers read it from the `connection`
  argument. Returns `{:error, :no_webhook_secret}` when unconfigured; the
  caller verifies nothing and does not run the handler.
  """
  @callback webhook_signing_secret(connection :: struct()) ::
              {:ok, webhook_secret()} | {:error, :no_webhook_secret}

  @doc """
  Optional. Resolves the signing secret from the connection and the ingest
  tenant, for secrets kept per tenant and connection. A provider using
  `use AshHooks.Provider` gets a
  default implementation delegating to `webhook_signing_secret/1` (existing
  providers compile unchanged); a per-tenant provider overrides `/2`.
  """
  @callback webhook_signing_secret(connection :: struct(), tenant :: term()) ::
              {:ok, webhook_secret()} | {:error, :no_webhook_secret}

  @doc """
  Declares whether this provider's webhook signing secret is app-level
  (the default) or per-connection. Optional.
  """
  @callback webhook_secret_scope() :: webhook_secret_scope()

  @doc """
  The request header this provider's signature scheme carries a trustworthy
  timestamp in (`nil` when the scheme has none). A DSL `replay_window_seconds`
  requires a non-`nil` value here: the compile-time verifier rejects the
  combination otherwise. Other provider-defined timestamp checks and JWS
  expiration and not-before checks can apply independently.
  Optional, defaulting to `nil`.
  """
  @callback timestamp_header() :: String.t() | nil

  @optional_callbacks webhook_signing_secret: 1,
                      webhook_signing_secret: 2,
                      webhook_secret_scope: 0,
                      timestamp_header: 0

  @doc """
  Defines a provider. With `verify: opts`, generates overridable verification,
  timestamp, signature-source, event-parsing, and handling callbacks from an
  `AshHooks.Provider.Scheme`; JWS-body providers also get a payload decoder and
  a payload-based `event_identity/1`. The options are checked when the module
  finishes compiling, so an invalid option is a compile error. Write them in
  place as a keyword list; their values may read module attributes set before the
  `use` line and may be
  two-argument anonymous functions (which may call the module's private
  functions), remote captures, or `{module, function}` tuples.

  Plain `use AshHooks.Provider` sets the behavior and provides the
  tenant-aware `webhook_signing_secret/2` as an overridable default that
  delegates to `webhook_signing_secret/1` when the provider implements it:
  implement `/1` and both shapes resolve; override `/2` for per-tenant
  secrets; implement neither and the default fails closed as
  `{:error, :no_webhook_secret}` (the optional-callback semantics: an
  app-level provider never sees the callback called at all). Providers written against the plain `@behaviour` keep working
  unchanged (`webhook_signing_secret/3` resolves both).
  """
  defmacro __using__(opts) do
    configured =
      case Keyword.fetch(opts, :verify) do
        :error -> nil
        {:ok, verify_opts} -> configured_callbacks(verify_opts)
      end

    quote do
      @behaviour AshHooks.Provider

      # dispatched dynamically: Elixir resolves same-name local calls at
      # COMPILE time, so a plain `webhook_signing_secret(connection)` here
      # is a compile error in providers that implement neither secret
      # callback. The apply also
      # lets the runtime branch fail closed for app-scope providers.
      unquote(if configured, do: quote(do: @impl(true)))

      def webhook_signing_secret(connection, _tenant) do
        if function_exported?(__MODULE__, :webhook_signing_secret, 1) do
          apply(__MODULE__, :webhook_signing_secret, [connection])
        else
          {:error, :no_webhook_secret}
        end
      end

      defoverridable webhook_signing_secret: 2
      unquote(configured)
    end
  end

  # Options are rebuilt inside the module on each call, so they may use
  # anonymous functions that call the module's own private helpers and read
  # its attributes. They are validated once the module has compiled
  # (`__after_compile__/2`), so a bad option is still a compile error. Only
  # the signature location is read at expansion: a JWS body provider gets a
  # payload decoder and a payload-based identity.
  defp configured_callbacks(verify_opts) do
    {options, jws?} = literal_options(verify_opts)
    source = if jws?, do: :body, else: :request

    quote do
      @after_compile AshHooks.Provider

      @doc false
      def __ash_hooks_scheme__, do: Scheme.new!(unquote(options))

      @impl true
      def verify_signature(raw_body, ctx, keys),
        do: Scheme.verify(raw_body, ctx, keys, __ash_hooks_scheme__())

      @impl true
      def timestamp_header, do: Scheme.timestamp_header(__ash_hooks_scheme__())
      @impl true
      def signature_source, do: unquote(source)
      @impl true
      def parse_event_type(payload), do: Event.parse(payload)
      @impl true
      def handle_event(type, payload), do: Event.build(type, payload)

      defoverridable verify_signature: 3,
                     timestamp_header: 0,
                     signature_source: 0,
                     parse_event_type: 1,
                     handle_event: 2

      unquote(jws_callbacks(jws?))
    end
  end

  defp jws_callbacks(false), do: nil

  defp jws_callbacks(true) do
    quote do
      @impl true
      def decode_payload(raw_body),
        do: Scheme.decode_payload(raw_body, __ash_hooks_scheme__())

      @impl true
      def event_identity(payload), do: Scheme.payload_identity(payload)

      defoverridable decode_payload: 1, event_identity: 1
    end
  end

  defp literal_options(options) when is_list(options) do
    if Keyword.keyword?(options),
      do: {options, Keyword.get(options, :signature) == :jws_body},
      else: raise(ArgumentError, "use AshHooks.Provider expects verify: to be a keyword list")
  end

  defp literal_options(_options) do
    raise ArgumentError,
          "use AshHooks.Provider expects verify: to be a keyword list written in place " <>
            "(its values may read module attributes or call the module's functions); to " <>
            "choose options at runtime, implement verify_signature/3 with " <>
            "AshHooks.Provider.Scheme.verify/4"
  end

  @doc false
  def __after_compile__(env, _bytecode) do
    _ = env.module.__ash_hooks_scheme__()
    :ok
  end

  @doc """
  Parses the event type from the decoded request body: a map for
  object-shaped deliveries, a list for batch deliveries. Providers receiving a
  shape their sender never sends
  fail closed through their catch-all clause (`{:error, :malformed_payload}`).
  """
  @callback parse_event_type(payload :: map() | list()) ::
              {:ok, atom()} | {:error, parse_error()}

  @doc "Converts a verified, parsed payload into the provider's typed event."
  @callback handle_event(event_type :: atom(), payload :: map() | list()) ::
              {:ok, typed_event :: struct()}
              | {:error, :retry | :permanent, term()}

  @doc """
  Returns a stable provider-defined identity for a decoded webhook payload.

  This callback is optional. Ingress uses it only when the inbound declaration
  has no explicit host `event_id` extractor. An implemented callback's error is
  authoritative and never falls back to the raw-body digest. Providers without
  the callback retain the raw-body SHA-256 identity behavior.
  """
  @callback event_identity(payload :: map() | list()) ::
              {:ok, String.t()} | {:error, :malformed_payload}

  @optional_callbacks event_identity: 1

  @doc """
  Optional payload decoder, called only after signature verification succeeds.
  Returns a map or list. Providers without it retain JSON decoding. A route's
  explicit `body_format` takes precedence. Custom decoders must return an error
  for malformed input. Decoder failures normally become permanent
  malformed-payload rows. If the provider's identity callback cannot derive
  an identity, ingress returns an error before creating the accepted row.
  """
  @callback decode_payload(raw_body()) :: {:ok, map() | list()} | {:error, term()}

  @doc "Optional payload format, defaulting to JSON; `:form` opts into flat form decoding."
  @callback body_format() :: :json | :form

  @optional_callbacks decode_payload: 1, body_format: 0

  @doc """
  Optional signature location: `:header` (default) requires the host-supplied
  `ctx.signature`; `:body` admits signed body envelopes; `:request` lets the
  provider extract signatures from request headers itself.
  """
  @callback signature_source() :: :header | :body | :request
  @optional_callbacks signature_source: 0

  @doc false
  def signature_source(provider) do
    if function_exported?(provider, :signature_source, 0),
      do: provider.signature_source(),
      else: :header
  end

  @doc "Dispatches the optional HTTP handshake; an absent callback continues delivery."
  @spec handshake(module(), handshake_request()) ::
          {:respond, pos_integer(), [{String.t(), String.t()}], iodata()} | :deliver
  def handshake(provider, request) do
    if Code.ensure_loaded?(provider) and function_exported?(provider, :handshake, 1),
      do: provider.handshake(request),
      else: :deliver
  end

  @doc "Dispatches the optional HTTP response policy; an absent callback returns `:default`."
  @spec response(module(), ingest_outcome()) :: http_response() | :default
  def response(provider, outcome) do
    if Code.ensure_loaded?(provider) and function_exported?(provider, :response, 1),
      do: provider.response(outcome),
      else: :default
  end

  @doc false
  def decode_payload(provider, raw_body, format) do
    cond do
      format ->
        decode_body(raw_body, format)

      function_exported?(provider, :decode_payload, 1) ->
        provider.decode_payload(raw_body)

      function_exported?(provider, :body_format, 0) ->
        decode_body(raw_body, provider.body_format())

      true ->
        decode_body(raw_body, :json)
    end
  end

  @doc false
  def decode_body(raw_body, :json), do: Jason.decode(raw_body)

  def decode_body(raw_body, :form) do
    payload = URI.decode_query(raw_body)

    if Enum.all?(payload, fn {name, value} -> String.valid?(name) and String.valid?(value) end),
      do: {:ok, payload},
      else: {:error, :malformed_payload}
  end

  @doc """
  Resolves a provider's webhook secret scope, defaulting to `:app_level` when
  the optional `webhook_secret_scope/0` callback is not implemented.

  Loads the provider module first: `function_exported?/3` reports false for a
  module that is not yet loaded, which would misread an unloaded
  per-connection provider as app-level.
  """
  @spec secret_scope(module()) :: webhook_secret_scope()
  def secret_scope(provider) when is_atom(provider) do
    if Code.ensure_loaded?(provider) and function_exported?(provider, :webhook_secret_scope, 0) do
      provider.webhook_secret_scope()
    else
      :app_level
    end
  end

  @doc """
  Resolves a provider's trustworthy timestamp header, defaulting to `nil`
  when the optional `timestamp_header/0` callback is not implemented.

  Loads the provider module first, with the same unloaded-module guard as
  `secret_scope/1`.
  """
  @spec timestamp_header(module()) :: String.t() | nil
  def timestamp_header(provider) when is_atom(provider) do
    if Code.ensure_loaded?(provider) and function_exported?(provider, :timestamp_header, 0) do
      provider.timestamp_header()
    else
      nil
    end
  end

  @doc """
  Resolves the optional stable event identity callback.

  `:not_supported` means the provider leaves identity to the raw request
  digest. Callback errors are returned unchanged for ingress to reject.
  """
  @spec event_identity(module(), map() | list()) ::
          :not_supported | {:ok, String.t()} | {:error, :malformed_payload}
  def event_identity(provider, payload) when is_atom(provider) do
    if Code.ensure_loaded?(provider) and function_exported?(provider, :event_identity, 1) do
      provider.event_identity(payload)
    else
      :not_supported
    end
  end

  @doc """
  Resolves the per-connection signing secret for an ingest: an overriding
  `webhook_signing_secret/2` (tenant-aware custody) wins; otherwise the
  call delegates to `webhook_signing_secret/1`, so providers of either
  implementation shape work through this one entry point.
  """
  @spec webhook_signing_secret(module(), struct(), term()) ::
          {:ok, webhook_secret()} | {:error, :no_webhook_secret}
  def webhook_signing_secret(provider, connection, tenant) when is_atom(provider) do
    if Code.ensure_loaded?(provider) and function_exported?(provider, :webhook_signing_secret, 2) do
      provider.webhook_signing_secret(connection, tenant)
    else
      provider.webhook_signing_secret(connection)
    end
  end

  @doc """
  Default HMAC verify implementation: lowercase-hex HMAC of the raw body under
  the secret, compared in constant time behind a byte-size guard.

  The byte-size guard both short-circuits wrong-length signatures and
  satisfies `:crypto.hash_equals/2`'s equal-length requirement.

  An EMPTY secret fails closed as `{:error, :no_webhook_secret}`: an HMAC
  under the empty key is computable by anyone, so a secret source that quietly
  resolves to `""` must not verify anything.
  """
  @spec default_verify_signature(
          raw_body(),
          signature_header_value(),
          webhook_secret(),
          signature_algorithm()
        ) :: :ok | {:error, :invalid_signature | :no_webhook_secret}

  def default_verify_signature(_raw_body, _header_value, secret, _algorithm)
      when byte_size(secret) == 0,
      do: {:error, :no_webhook_secret}

  def default_verify_signature(raw_body, header_value, secret, algorithm)
      when is_binary(raw_body) and is_binary(header_value) and is_binary(secret) and
             algorithm in [:hmac_sha256, :hmac_sha512] do
    digest = if(algorithm == :hmac_sha256, do: :sha256, else: :sha512)

    expected =
      :crypto.mac(:hmac, digest, secret, raw_body) |> Base.encode16(case: :lower)

    if byte_size(expected) == byte_size(header_value) and
         :crypto.hash_equals(expected, header_value) do
      :ok
    else
      {:error, :invalid_signature}
    end
  end
end
